#!/usr/bin/env python3
# gen-sensor-regs.py - emit C register tables for the a52q IMX616 / S5KGW1P
# V4L2 drivers from the CamX sensor-module JSON decoded by camx-sensormodule.py.
#
# regSettings layout (per the decoder): indices 0..N-1 are the per-mode register
# lists (same order as `modes`), then stream-on, stream-off, group-hold on/off,
# then the resolution-independent init (the largest list). Each register entry is
# [addr, value, addrBytes, dataBytes, delayUs]. The sensors are 16-bit-address
# devices, so address is always emitted as 16-bit; `len` is the data width.
#
# Usage: gen-sensor-regs.py <decoded.json> <prefix> <init_idx> <mode_idx> > out.h
import sys, json

def emit(name, regs):
    # Emit media/v4l2-cci.h cci_reg_sequence tables: {CCI_REG8/16(addr), val}.
    print(f"static const struct cci_reg_sequence {name}[] = {{")
    line = "\t"
    for i, e in enumerate(regs):
        addr, val, _abytes, dbytes, _delay = e
        macro = "CCI_REG8" if dbytes == 1 else "CCI_REG16"
        tok = f"{{{macro}(0x{addr:04x}), 0x{val:04x}}}, "
        if len(line) + len(tok) > 96:
            print(line.rstrip())
            line = "\t"
        line += tok
    if line.strip():
        print(line.rstrip())
    print("};\n")

def main():
    global PREFIX
    path, PREFIX, init_idx, mode_idx = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4])
    d = json.load(open(path))
    rs = d["regSettings"]
    m = d["modes"][mode_idx]
    print(f"/* Generated by gen-sensor-regs.py from {d.get('sensorName','?')} */")
    print(f"/* mode[{mode_idx}]: line_length={m['lineLength']} frame_length={m['frameLength']}"
          f" op_pixel_clock={m['opPixelClock']} fps={m['fps']} */\n")
    emit(f"{PREFIX}_init", rs[init_idx]["registers"])
    emit(f"{PREFIX}_mode_regs", rs[mode_idx]["registers"])

if __name__ == "__main__":
    main()
